export const BANK_LINES: BankLine[] = (() => {
  let balance = OPENING_BANK;
  return BANK_RAW.map(
    ([date, description, ref, value, match, voucherNo], i) => {
      balance += value;
      return {
        id: `b-${i + 1}`,
        date,
        description,
        ref,
        debit: value < 0 ? -value : undefined,
        credit: value > 0 ? value : undefined,
        balance,
        match,
        voucherNo,
      };
    },
  );
})();

