const GST_CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";

function gstin(pan: string, state = "27", entity = "1"): string {
  const base = `${state}${pan}${entity}Z`;
  let sum = 0;
  for (let i = 0; i < base.length; i++) {
    const v = GST_CHARS.indexOf(base[i] ?? "0");
    const p = v * (i % 2 === 0 ? 1 : 2);
    sum += Math.floor(p / 36) + (p % 36);
  }
  return base + GST_CHARS[(36 - (sum % 36)) % 36];
}

